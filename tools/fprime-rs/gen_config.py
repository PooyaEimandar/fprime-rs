#!/usr/bin/env python3
"""Generate the fprime-rs configuration crate from the FPP configuration files.

The C++ build derives its type widths from FPP alias files; Rust must derive
them from the same source or the wire formats drift. This tool parses:

  - a platform FPP alias file (PlatformSizeType and friends)
  - one or more config FPP files (Fw* aliases, possibly chained through
    Platform*; FpConfig.fpp is required, others like ComCfg.fpp optional)
  - config/FpConstants.fpp (wire constants such as the bool encoding)

and emits:

  - a Rust module of `pub type` aliases and constants (--out)
  - a C++ translation unit of static_asserts comparing sizeof() of the real
    C++ config types against the widths the Rust crate was generated with
    (--out-cpp). Compiled into the Rust_Codec module, this is the
    authoritative cross-language drift check: if a project changes a width in
    its FPP config without regenerating the Rust crate, the C++ build fails.
    Every parsed Fw alias is checked (all are exported via
    Fw/FPrimeBasicTypes.h; an alias missing there fails the check compile,
    which is the desired loud behavior).

Usage:
  gen_config.py --platform <PlatformTypes.fpp> --config <FpConfig.fpp> [more...] \
                --constants <FpConstants.fpp> --out <lib.rs> --out-cpp <check.cpp>
"""

import argparse
import re
import sys
from pathlib import Path

FPP_TO_RUST = {
    "U8": "u8",
    "U16": "u16",
    "U32": "u32",
    "U64": "u64",
    "I8": "i8",
    "I16": "i16",
    "I32": "i32",
    "I64": "i64",
    "F32": "f32",
    "F64": "f64",
}

TYPE_RE = re.compile(r"^\s*(?:dictionary\s+)?type\s+(\w+)\s*=\s*(\w+)\s*(?:@.*)?$")
CONST_RE = re.compile(
    r"^\s*(?:dictionary\s+)?constant\s+(\w+)\s*=\s*(0x[0-9A-Fa-f]+|-?\d+)\s*(?:@.*)?$"
)


def parse_aliases(path: Path) -> dict:
    aliases = {}
    for line in path.read_text().splitlines():
        m = TYPE_RE.match(line)
        if m:
            aliases[m.group(1)] = m.group(2)
    return aliases


def parse_constants(path: Path) -> dict:
    consts = {}
    for line in path.read_text().splitlines():
        m = CONST_RE.match(line)
        if m:
            consts[m.group(1)] = m.group(2)
    return consts


def resolve(name: str, aliases: dict, seen=None) -> str:
    seen = seen or set()
    if name in FPP_TO_RUST:
        return FPP_TO_RUST[name]
    if name in seen:
        sys.exit(f"error: alias cycle at {name}")
    seen.add(name)
    if name not in aliases:
        sys.exit(f"error: {name} is not defined and is not a base FPP type")
    return resolve(aliases[name], aliases, seen)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--platform", required=True, type=Path)
    ap.add_argument(
        "--config",
        required=True,
        type=Path,
        nargs="+",
        help="FPP config files; the first must be FpConfig.fpp (its aliases are C++-checked)",
    )
    ap.add_argument("--constants", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--out-cpp", required=True, type=Path)
    args = ap.parse_args()

    aliases = parse_aliases(args.platform)
    for config in args.config:
        aliases.update(parse_aliases(config))
    consts = parse_constants(args.constants)

    fw_names = sorted(n for n in aliases if n.startswith("Fw"))
    resolved = {n: resolve(n, aliases) for n in fw_names}
    widths = {n: int(r[1:]) // 8 for n, r in resolved.items()}

    # --- Rust crate ---
    lines = [
        "//! F Prime configuration type aliases and wire constants.",
        "//!",
        "//! GENERATED by tools/fprime-rs/gen_config.py -- do not edit by hand.",
        "//! Regenerate whenever the FPP config or platform alias files change;",
        "//! these widths define the wire format. The authoritative drift check",
        "//! is Rust/RustConfigCheck.cpp (generated alongside this file), which",
        "//! the C++ build compiles: a width change that is not regenerated here",
        "//! fails the C++ build.",
        "#![no_std]",
        "",
    ]
    for name in fw_names:
        lines.append(f"pub type {name} = {resolved[name]};")
    lines.append("")
    for cname in ("FW_SERIALIZE_TRUE_VALUE", "FW_SERIALIZE_FALSE_VALUE"):
        if cname in consts:
            lines.append(f"pub const {cname}: u8 = {consts[cname]};")
    lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))

    # --- C++ cross-check TU ---
    cpp = [
        "// GENERATED by tools/fprime-rs/gen_config.py -- do not edit by hand.",
        "//",
        "// Cross-language configuration drift check: each static_assert compares",
        "// a real C++ config type against the width the Rust fprime-config crate",
        "// was generated with. If a project changes an FPP type width without",
        "// regenerating the Rust crate, this translation unit fails to compile,",
        "// stopping the wire-format divergence at build time.",
        "",
        "#include <Fw/FPrimeBasicTypes.hpp>",
        "",
    ]
    for name in fw_names:
        cpp.append(
            f"static_assert(sizeof({name}) == {widths[name]}, "
            f'"{name} width changed: regenerate Rust/fprime-config (tools/fprime-rs/gen_config.py)");'
        )
    cpp.append("")
    for cname in ("FW_SERIALIZE_TRUE_VALUE", "FW_SERIALIZE_FALSE_VALUE"):
        if cname in consts:
            cpp.append(
                f"static_assert(static_cast<unsigned int>({cname}) == {consts[cname]}u, "
                f'"{cname} changed: regenerate Rust/fprime-config");'
            )
    cpp.append("")
    args.out_cpp.write_text("\n".join(cpp))
    print(
        f"wrote {args.out} ({len(fw_names)} aliases) and {args.out_cpp} ({len(fw_names)} checked)"
    )


if __name__ == "__main__":
    main()
